import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import { resolve } from 'node:path';

const root = fileURLToPath(new URL('../../', import.meta.url));
// Resolve the existing exact locked web toolchain, not an ambient binary.
const require = createRequire(resolve(root, 'web/package.json'));
const { rolldown } = await import(require.resolve('rolldown'));
const bundle = await rolldown({ cwd: root, platform: 'browser', input: resolve(root, 'scripts/cast/contracts.ts') });
try {
  await bundle.write({
    file: resolve(root, 'server/receiver/cast/contracts.js'),
    format: 'iife', name: 'PorticoCastContracts',
    banner: '// Generated by node scripts/cast/generate.mjs from canonical apigen contracts. Do not edit.',
    sourcemap: false,
  });
} finally {
  await bundle.close();
}
