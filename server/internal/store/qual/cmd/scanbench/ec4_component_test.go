package main

import (
	"bytes"
	"encoding/json"
	"os"
	"path/filepath"
	"runtime"
	"strings"
	"testing"
)

// Functional component smoke only. Both profiles use the runner's filesystem;
// a requested HDD label supplies neither an IO limit nor HDD qualification.
func TestEC4SmallFixtureProfiles(t *testing.T) {
	if runtime.GOOS != "linux" {
		t.Skip("native Linux cookies")
	}
	scratch := t.TempDir()
	seed := filepath.Join(scratch, "seed.mkv")
	if err := os.WriteFile(seed, []byte("bounded traversal payload; no Basic/media probe"), 0600); err != nil {
		t.Fatal(err)
	}
	root := filepath.Join(scratch, "library")
	var generated bytes.Buffer
	if err := run(t.Context(), []string{"-mode", "generate", "-root", root, "-template", seed, "-files", "16"}, &generated); err != nil {
		t.Fatal(err)
	}
	assertQualificationFalse(t, generated.Bytes())
	for _, profile := range []string{"ssd", "throttled-hdd"} {
		t.Run(profile, func(t *testing.T) {
			var output bytes.Buffer
			if err := run(t.Context(), []string{"-root", root, "-source-sha", strings.Repeat("a", 40), "-storage", profile}, &output); err != nil {
				t.Fatal(err)
			}
			assertQualificationFalse(t, output.Bytes())
			var result report
			if err := json.Unmarshal(output.Bytes(), &result); err != nil {
				t.Fatal(err)
			}
			if result.Counts.Files != 16 || !result.TraversalCompleted || result.RequestedStorage != profile || result.Engine != nil || result.FilenameVisibleNS != nil || result.BasicNS != nil {
				t.Fatal("component traversal became acceptance/visibility/Basic", result)
			}
			if evidence := os.Getenv("PORTICO_LANE_EVIDENCE_DIR"); evidence != "" {
				// The workflow's receipt supplies the exact source/toolchain. The repeated
				// 'a' above is explicitly a declared test input, not that source identity.
				data, err := json.Marshal(struct {
					Label             string   `json:"label"`
					Qualification     bool     `json:"qualification"`
					NativeFiles       uint64   `json:"native_files"`
					RequestedStorage  string   `json:"requested_storage"`
					ActualThrottle    bool     `json:"actual_throttle"`
					FilenameVisibleNS *int64   `json:"filename_visible_ns"`
					BasicNS           *int64   `json:"basic_ns"`
					Missing           []string `json:"missing"`
				}{"COMPONENT_ONLY", false, result.Counts.Files, profile, false, nil, nil, result.Unavailable})
				if err != nil {
					t.Fatal(err)
				}
				if err := os.MkdirAll(evidence, 0700); err != nil {
					t.Fatal(err)
				}
				if err := os.WriteFile(filepath.Join(evidence, "ec4-"+profile+".json"), append(data, '\n'), 0600); err != nil {
					t.Fatal(err)
				}
			}
		})
	}
}
