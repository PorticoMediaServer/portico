package dbwork

import (
	"bytes"
	"flag"
	"fmt"
	"go/ast"
	"go/parser"
	"go/printer"
	"go/token"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
	"testing"
)

var updateCensus = flag.Bool("update-write-census", false, "rewrite testdata/write_census.tsv from the source")

// writeHelpers are the calls that open a gated write. Each one is a place where
// a WritePlan applies: its class default, or a named plan passed with WithPlan.
var writeHelpers = map[string]bool{"Begin": true, "WithWriteTx": true, "WithWriteTxContext": true, "ExecWrite": true, "ReserveWriterConn": true}

const dbworkImport = "github.com/PorticoMediaServer/portico/server/internal/dbwork"

type censusSite struct {
	file, function, helper, class, plan string
}

// censusPlan is one WithPlan or UsePlan declaration, wherever it sits relative
// to the write it governs.
type censusPlan struct {
	file, function, plan string
}

func (s censusSite) String() string {
	return strings.Join([]string{s.file, s.function, s.helper, s.class, s.plan}, "\t")
}

// TestWriteCensus is the static census of every gated write in the server. A
// new write site, a changed class or a newly declared plan shows up as a diff
// of testdata/write_census.tsv, so it is reviewed with the code; the runtime
// half (plan.go) measures each one against its plan.
//
// Regenerate with: go test ./internal/dbwork -run TestWriteCensus -update-write-census
func TestWriteCensus(t *testing.T) {
	root, err := filepath.Abs("../..")
	if err != nil {
		t.Fatal(err)
	}
	var sites []censusSite
	var declared []censusPlan
	plansWithoutReason := []string{}
	for _, dir := range []string{"internal", "cmd"} {
		err := filepath.Walk(filepath.Join(root, dir), func(path string, info os.FileInfo, err error) error {
			if err != nil {
				return err
			}
			if info.IsDir() || !strings.HasSuffix(path, ".go") || strings.HasSuffix(path, "_test.go") {
				return nil
			}
			relative, _ := filepath.Rel(root, path)
			relative = filepath.ToSlash(relative)
			found, plans, unreasoned, err := censusFile(path, relative)
			sites = append(sites, found...)
			declared = append(declared, plans...)
			plansWithoutReason = append(plansWithoutReason, unreasoned...)
			return err
		})
		if err != nil {
			t.Fatal(err)
		}
	}
	if len(plansWithoutReason) > 0 {
		t.Errorf("a named WritePlan must say Why it cannot be split into class-sized transactions:\n%s", strings.Join(plansWithoutReason, "\n"))
	}
	counts := map[string]int{}
	for _, site := range sites {
		counts[site.String()]++
	}
	lines := make([]string, 0, len(counts))
	for line, count := range counts {
		if count > 1 {
			line += "\t×" + strconv.Itoa(count)
		}
		lines = append(lines, line)
	}
	sort.Strings(lines)
	planLines := []string{}
	for _, p := range declared {
		planLines = append(planLines, strings.Join([]string{"plan", p.file, p.function, p.plan}, "\t"))
	}
	sort.Strings(planLines)
	got := "# file\tfunction\thelper\tclass\tplan (generated by TestWriteCensus; review every change)\n" + strings.Join(lines, "\n") + "\n" +
		"# every declared plan: plan\tfile\tfunction\tplan\n" + strings.Join(planLines, "\n") + "\n"
	path := filepath.Join("testdata", "write_census.tsv")
	if *updateCensus {
		if err := os.MkdirAll("testdata", 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, []byte(got), 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	want, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("%v; run go test ./internal/dbwork -run TestWriteCensus -update-write-census", err)
	}
	if string(want) != got {
		t.Fatalf("the write census changed; review the diff and run go test ./internal/dbwork -run TestWriteCensus -update-write-census\n%s", censusDiff(string(want), got))
	}
}

func censusFile(path, relative string) ([]censusSite, []censusPlan, []string, error) {
	fset := token.NewFileSet()
	file, err := parser.ParseFile(fset, path, nil, parser.SkipObjectResolution)
	if err != nil {
		return nil, nil, nil, err
	}
	inDBWork := strings.HasPrefix(relative, "internal/dbwork/")
	local := ""
	for _, spec := range file.Imports {
		if value, _ := strconv.Unquote(spec.Path.Value); value == dbworkImport {
			local = "dbwork"
			if spec.Name != nil {
				local = spec.Name.Name
			}
		}
	}
	if local == "" && !inDBWork {
		return nil, nil, nil, nil
	}
	helperOf := func(call *ast.CallExpr) (string, bool) {
		switch fn := call.Fun.(type) {
		case *ast.SelectorExpr:
			if x, ok := fn.X.(*ast.Ident); ok && x.Name == local && writeHelpers[fn.Sel.Name] {
				return fn.Sel.Name, true
			}
		case *ast.Ident:
			if inDBWork && writeHelpers[fn.Name] {
				return fn.Name, true
			}
		}
		return "", false
	}
	// WithPlan(ctx, plan) and UsePlan(tx, plan) both name a site's plan.
	isWithPlan := func(call *ast.CallExpr) bool {
		switch fn := call.Fun.(type) {
		case *ast.SelectorExpr:
			x, ok := fn.X.(*ast.Ident)
			return ok && x.Name == local && (fn.Sel.Name == "WithPlan" || fn.Sel.Name == "UsePlan")
		case *ast.Ident:
			return inDBWork && (fn.Name == "WithPlan" || fn.Name == "UsePlan")
		}
		return false
	}
	var sites []censusSite
	var plans []censusPlan
	var unreasoned []string
	for _, decl := range file.Decls {
		fn, ok := decl.(*ast.FuncDecl)
		if !ok || fn.Body == nil {
			continue
		}
		name := fn.Name.Name
		if fn.Recv != nil && len(fn.Recv.List) == 1 {
			name = "(" + render(fset, fn.Recv.List[0].Type) + ")." + name
		}
		plan := "-"
		ast.Inspect(fn.Body, func(node ast.Node) bool {
			if call, ok := node.(*ast.CallExpr); ok && isWithPlan(call) && len(call.Args) == 2 {
				plans = append(plans, censusPlan{file: relative, function: name, plan: render(fset, call.Args[1])})
				if plan == "-" {
					plan = render(fset, call.Args[1])
				} else if !strings.Contains(plan, render(fset, call.Args[1])) {
					plan += "|" + render(fset, call.Args[1])
				}
				if literal, ok := call.Args[1].(*ast.CompositeLit); ok && !hasReason(literal) {
					unreasoned = append(unreasoned, fmt.Sprintf("%s:%d", relative, fset.Position(call.Pos()).Line))
				}
			}
			return true
		})
		ast.Inspect(fn.Body, func(node ast.Node) bool {
			call, ok := node.(*ast.CallExpr)
			if !ok {
				return true
			}
			helper, ok := helperOf(call)
			if !ok {
				return true
			}
			class := "?"
			if len(call.Args) > 2 {
				class = strings.TrimPrefix(render(fset, call.Args[2]), local+".")
			}
			sites = append(sites, censusSite{file: relative, function: name, helper: helper, class: class, plan: plan})
			return true
		})
	}
	// A plan declared as a package-level value must say why, too.
	for _, decl := range file.Decls {
		general, ok := decl.(*ast.GenDecl)
		if !ok || general.Tok != token.VAR {
			continue
		}
		for _, spec := range general.Specs {
			for _, value := range spec.(*ast.ValueSpec).Values {
				literal, ok := value.(*ast.CompositeLit)
				if !ok {
					continue
				}
				typeName := render(fset, literal.Type)
				if (typeName == local+".WritePlan" || inDBWork && typeName == "WritePlan") && !hasReason(literal) {
					unreasoned = append(unreasoned, fmt.Sprintf("%s:%d", relative, fset.Position(literal.Pos()).Line))
				}
			}
		}
	}
	return sites, plans, unreasoned, nil
}

func hasReason(literal *ast.CompositeLit) bool {
	for _, element := range literal.Elts {
		pair, ok := element.(*ast.KeyValueExpr)
		if !ok {
			continue
		}
		if key, ok := pair.Key.(*ast.Ident); ok && key.Name == "Why" {
			if value, ok := pair.Value.(*ast.BasicLit); ok {
				text, _ := strconv.Unquote(value.Value)
				return strings.TrimSpace(text) != ""
			}
			return true
		}
	}
	return false
}

func render(fset *token.FileSet, node ast.Node) string {
	if node == nil {
		return ""
	}
	var out bytes.Buffer
	_ = printer.Fprint(&out, fset, node)
	return strings.Join(strings.Fields(out.String()), " ")
}

func censusDiff(want, got string) string {
	wanted := map[string]bool{}
	for _, line := range strings.Split(want, "\n") {
		wanted[line] = true
	}
	have := map[string]bool{}
	for _, line := range strings.Split(got, "\n") {
		have[line] = true
	}
	var out []string
	for _, line := range strings.Split(want, "\n") {
		if !have[line] {
			out = append(out, "- "+line)
		}
	}
	for _, line := range strings.Split(got, "\n") {
		if !wanted[line] {
			out = append(out, "+ "+line)
		}
	}
	if len(out) > 40 {
		out = append(out[:40], fmt.Sprintf("… and %d more", len(out)-40))
	}
	return strings.Join(out, "\n")
}
