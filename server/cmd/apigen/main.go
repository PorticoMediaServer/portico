// apigen emits contracts from the registry consumed by the server router.
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"github.com/PorticoMediaServer/portico/apikit"
	"github.com/PorticoMediaServer/portico/server/internal/httpapi"
	"github.com/PorticoMediaServer/portico/server/internal/qualityladder"
)

func main() {
	root := flag.String("root", "..", "Repository root")
	development := flag.Bool("development", false, "Generate only development contracts (requires devtrust) under packages/contracts/src/development")
	flag.Parse()
	registry, err := httpapi.FoundationRegistry(httpapi.Dependencies{})
	if err != nil {
		fail(err)
	}
	components, wire, err := httpapi.PublishedSchemas()
	if err != nil {
		fail(err)
	}
	definitions := registry.Definitions()
	if *development {
		definitions = nil
		for _, definition := range registry.Definitions() {
			if strings.HasPrefix(definition.Path, "/v1/dev/") {
				definitions = append(definitions, definition)
			}
		}
		if len(definitions) == 0 {
			fail(fmt.Errorf("development contracts require a devtrust build"))
		}
	}
	artifacts, err := apikit.GenerateWith(definitions, apikit.Options{Errors: registry.ErrorDefinitions(), Components: components, WireSchemas: wire, GrandfatheredUnionTags: grandfatheredFor(definitions), RequireGrandfatheredUse: true})
	if err != nil {
		fail(err)
	}
	// Client vocabulary is emitted from the producer's canonical data, never
	// maintained as a second client-side bitrate table.
	vocabulary := []map[string]any{{"id": "original", "label": "Original", "height": 0, "videoKbps": 0, "audioKbps": 0, "dataGBPerHour": nil}, {"id": "automatic", "label": "Automatic", "height": 0, "videoKbps": 0, "audioKbps": 0, "dataGBPerHour": nil}}
	for _, p := range qualityladder.Fixed() {
		vocabulary = append(vocabulary, map[string]any{"id": p.ID, "label": p.Label, "height": p.Height, "videoKbps": p.VideoBitrateBPS / 1000, "audioKbps": p.MaxAudioBitrateBPS / 1000, "dataGBPerHour": p.DataGBPerHour})
	}
	rawVocabulary, err := json.MarshalIndent(vocabulary, "", "  ")
	if err != nil {
		fail(err)
	}
	vocabularyTS := []byte("// Generated by apigen from qualityladder. Do not edit.\nexport const canonicalQualityLadder = " + string(rawVocabulary) + " as const;\n")
	rawMusic, err := json.MarshalIndent(qualityladder.Music(), "", "  ")
	if err != nil {
		fail(err)
	}
	vocabularyTS = append(vocabularyTS, []byte("export const canonicalMusicQualityLadder = "+string(rawMusic)+" as const;\n")...)
	artifacts.Typescript = append(artifacts.Typescript, append([]byte("\n"), vocabularyTS...)...)
	if !*development {
		if err = os.WriteFile(filepath.Join(*root, "packages/player-core/src/quality-ladder.ts"), vocabularyTS, 0644); err != nil {
			fail(err)
		}
	}
	if *development {
		for name, raw := range map[string][]byte{"runtime.ts": artifacts.Runtime, "index.ts": artifacts.Index, "errors.ts": artifacts.Errors, "limits.ts": artifacts.Limits, "decoders.ts": artifacts.Decoders, "types.ts": artifacts.Typescript, "routes.ts": artifacts.Routes, "route-paths.ts": artifacts.RoutePaths, "schemas.ts": artifacts.Schemas} {
			target := filepath.Join(*root, "packages/contracts/src/development", name)
			if err = os.MkdirAll(filepath.Dir(target), 0755); err != nil {
				fail(err)
			}
			if err = os.WriteFile(target, raw, 0644); err != nil {
				fail(err)
			}
		}
		return
	}

	var lanes bytes.Buffer
	lanes.WriteString("// Generated by apigen. Do not edit.\npackage httpapi\n\n// routeLanes is a projection of the live API metadata plus non-API infrastructure.\nvar routeLanes = map[string]string{\n")
	sort.Slice(definitions, func(i, j int) bool {
		return definitions[i].Method+" "+definitions[i].Path < definitions[j].Method+" "+definitions[j].Path
	})
	for _, route := range definitions {
		if route.Admission == "" {
			fail(fmt.Errorf("%s has no admission class", route.ID))
		}
		fmt.Fprintf(&lanes, "%q: %q,\n", route.Method+" "+route.Path, route.Admission)
	}
	for _, pattern := range []string{"GET ", "POST ", "PUT ", "/", "/dlna/", "GET /receiver/cast/"} {
		fmt.Fprintf(&lanes, "%q: %q,\n", pattern, "default")
	}
	// DLNA media bodies stream for as long as a player plays.
	fmt.Fprintf(&lanes, "%q: %q,\n", "/dlna/media/", "media-body")
	lanes.WriteString("}\n")
	generatedLanes, err := format.Source(lanes.Bytes())
	if err != nil {
		fail(err)
	}
	for name, raw := range map[string][]byte{
		"server/internal/httpapi/route_lanes.go": generatedLanes,
		"packages/contracts/src/runtime.ts":      artifacts.Runtime,
		"packages/contracts/src/index.ts":        artifacts.Index,
		"server/api/portico.openapi.json":        artifacts.OpenAPI,
		"packages/contracts/src/errors.ts":       artifacts.Errors,
		"packages/contracts/src/limits.ts":       artifacts.Limits,
		"packages/contracts/src/decoders.ts":     artifacts.Decoders,
		"packages/contracts/src/types.ts":        artifacts.Typescript,
		"packages/contracts/src/routes.ts":       artifacts.Routes,
		"packages/contracts/src/route-paths.ts":  artifacts.RoutePaths,
		"packages/contracts/src/schemas.ts":      artifacts.Schemas,
	} {
		target := filepath.Join(*root, name)
		if err = os.MkdirAll(filepath.Dir(target), 0755); err != nil {
			fail(err)
		}
		if err = os.WriteFile(target, raw, 0644); err != nil {
			fail(err)
		}
	}
}

// grandfatheredFor keeps only the grandfathered tags of the routes being
// generated (keyed "routeID path"). Development generation selects only the
// /v1/dev/ routes, so requiring every production entry there would always fail.
func grandfatheredFor(definitions []apikit.Definition) map[string]string {
	ids := map[string]bool{}
	for _, d := range definitions {
		ids[d.ID] = true
	}
	out := map[string]string{}
	for key, tag := range httpapi.GrandfatheredUnionTags {
		if id, _, ok := strings.Cut(key, " "); ok && ids[id] {
			out[key] = tag
		}
	}
	return out
}

func fail(err error) { fmt.Fprintln(os.Stderr, err); os.Exit(1) }
