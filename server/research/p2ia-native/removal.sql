CREATE TABLE catalog_removal_progress(
 kind TEXT NOT NULL CHECK(kind IN('library','folder')),
 target TEXT NOT NULL,
 original_operation_id BLOB NOT NULL UNIQUE CHECK(length(original_operation_id)=16),
 original_request_digest BLOB NOT NULL CHECK(length(original_request_digest)=32),
 command_incarnation BLOB NOT NULL CHECK(length(command_incarnation)=16),
 original_library_id INTEGER NOT NULL REFERENCES catalog_libraries(id) ON DELETE NO ACTION ON UPDATE NO ACTION,
 original_library_key TEXT NOT NULL CHECK(length(original_library_key)>0),
 original_resolved_root TEXT NOT NULL CHECK(length(original_resolved_root)>0 AND instr(original_resolved_root,char(0))=0),
 original_source_incarnation TEXT,
 original_source_generation INTEGER,
 original_root_identity TEXT,
 last_command_sequence INTEGER NOT NULL DEFAULT 0 CHECK(last_command_sequence>=0),
 acknowledged_command_sequence INTEGER NOT NULL DEFAULT 0 CHECK(acknowledged_command_sequence>=0),
 receipt_reclaim_sequence INTEGER NOT NULL DEFAULT 0 CHECK(receipt_reclaim_sequence>=0),
 receipt_retained_count INTEGER NOT NULL DEFAULT 0 CHECK(receipt_retained_count>=0),
 receipt_retained_bytes INTEGER NOT NULL DEFAULT 0 CHECK(receipt_retained_bytes>=0),
 retirement_state TEXT NOT NULL DEFAULT 'retiring' CHECK(retirement_state IN('retiring','complete')),
 phase INTEGER NOT NULL DEFAULT 0 CHECK(phase BETWEEN 0 AND 5),
 entity_kind INTEGER NOT NULL DEFAULT 0,
 entity_cursor INTEGER NOT NULL DEFAULT 0,
 object_cursor TEXT NOT NULL DEFAULT '',
 walk_removed INTEGER NOT NULL DEFAULT 0 CHECK(walk_removed IN(0,1)),
 walk_kept INTEGER NOT NULL DEFAULT 0 CHECK(walk_kept IN(0,1)),
 job_lease_owner INTEGER NOT NULL DEFAULT 0 CHECK(job_lease_owner>=0),
 job_lease_generation INTEGER NOT NULL DEFAULT 0 CHECK(job_lease_generation>=0),
 job_lease_expires_ms INTEGER NOT NULL DEFAULT 0 CHECK(job_lease_expires_ms>=0),
 job_attempts INTEGER NOT NULL DEFAULT 0 CHECK(job_attempts BETWEEN 0 AND 4294967295),
 job_next_attempt_ms INTEGER CHECK(job_next_attempt_ms IS NULL OR job_next_attempt_ms>=0),
 job_due_ms INTEGER GENERATED ALWAYS AS (CASE WHEN job_next_attempt_ms IS NULL THEN NULL ELSE max(job_next_attempt_ms,job_lease_expires_ms) END) STORED,
 job_revision INTEGER NOT NULL DEFAULT 1 CHECK(job_revision>0),
 CHECK(original_library_id>0),
 CHECK((kind='folder')=(original_source_incarnation IS NOT NULL)),
 CHECK((kind='folder')=(original_source_generation IS NOT NULL)),
 CHECK((kind='folder')=(original_root_identity IS NOT NULL)),
 CHECK(original_source_incarnation IS NULL OR length(original_source_incarnation)>0),
 CHECK(original_source_generation IS NULL OR original_source_generation>0),
 CHECK(original_root_identity IS NULL OR length(original_root_identity)>0),
 CHECK(receipt_reclaim_sequence<=acknowledged_command_sequence AND acknowledged_command_sequence<=last_command_sequence),
 CHECK(retirement_state<>'complete' OR phase=5),
 CHECK((receipt_retained_count=0)=(receipt_retained_bytes=0)),
 CHECK(typeof(original_operation_id)='blob'),
 CHECK(typeof(original_request_digest)='blob'),
 CHECK(typeof(command_incarnation)='blob'),
 CHECK(typeof(original_library_id)='integer'),
 CHECK(typeof(original_library_key)='text'),
 CHECK(typeof(original_resolved_root)='text'),
 CHECK(typeof(original_source_incarnation) IN('null','text')),
 CHECK(typeof(original_source_generation) IN('null','integer')),
 CHECK(typeof(original_root_identity) IN('null','text')),
 CHECK(typeof(last_command_sequence)='integer'),
 CHECK(typeof(acknowledged_command_sequence)='integer'),
 CHECK(typeof(receipt_reclaim_sequence)='integer'),
 CHECK(typeof(receipt_retained_count)='integer'),
 CHECK(typeof(receipt_retained_bytes)='integer'),
 CHECK(typeof(retirement_state)='text'),
 PRIMARY KEY(kind,target),
 CHECK(typeof("kind")IN('null','text')),
 CHECK(typeof("target")IN('null','text')),
 CHECK(typeof("phase")IN('null','integer')),
 CHECK(typeof("entity_kind")IN('null','integer')),
 CHECK(typeof("entity_cursor")IN('null','integer')),
 CHECK(typeof("object_cursor")IN('null','text')),
 CHECK(typeof("walk_removed")IN('null','integer')),
 CHECK(typeof("walk_kept")IN('null','integer')),
 CHECK(typeof("job_lease_owner")IN('null','integer')),
 CHECK(typeof("job_lease_generation")IN('null','integer')),
 CHECK(typeof("job_lease_expires_ms")IN('null','integer')),
 CHECK(typeof("job_attempts")IN('null','integer')),
 CHECK(typeof("job_next_attempt_ms")IN('null','integer')),
 CHECK(typeof("job_revision")IN('null','integer'))
) WITHOUT ROWID;
CREATE TABLE catalog_removal_receipts(
 original_operation_id BLOB NOT NULL CHECK(length(original_operation_id)=16),
 command_incarnation BLOB NOT NULL CHECK(length(command_incarnation)=16),
 command_sequence INTEGER NOT NULL CHECK(command_sequence>0),
 operation_id BLOB NOT NULL UNIQUE CHECK(length(operation_id)=16),
 request_digest BLOB NOT NULL CHECK(length(request_digest)=32),
 command_kind TEXT NOT NULL CHECK(command_kind IN('retire_library','retire_source','retire_step')),
 result_version INTEGER NOT NULL CHECK(result_version=1),
 accepted_revision INTEGER NOT NULL CHECK(accepted_revision>0),
 applied_ms INTEGER NOT NULL CHECK(applied_ms>=0),
 result_kind TEXT NOT NULL CHECK(result_kind IN('library','folder')),
 result_target TEXT NOT NULL CHECK(length(result_target)>0),
 result_phase INTEGER NOT NULL CHECK(result_phase BETWEEN 0 AND 5),
 result_entity_kind INTEGER NOT NULL CHECK(result_entity_kind>=0),
 result_entity_cursor INTEGER NOT NULL CHECK(result_entity_cursor>=0),
 result_object_cursor TEXT NOT NULL,
 result_walk_removed INTEGER NOT NULL CHECK(result_walk_removed IN(0,1)),
 result_walk_kept INTEGER NOT NULL CHECK(result_walk_kept IN(0,1)),
 result_state TEXT NOT NULL CHECK(result_state IN('retiring','complete')),
 result_count INTEGER NOT NULL CHECK(result_count=0),
 result_digest BLOB NOT NULL CHECK(length(result_digest)=32),
 retained_bytes INTEGER NOT NULL CHECK(retained_bytes>0),
 CONSTRAINT ia_retained_payload_bytes CHECK(retained_bytes=200+length(CAST(command_kind AS BLOB))+length(CAST(result_kind AS BLOB))+length(CAST(result_target AS BLOB))+length(CAST(result_object_cursor AS BLOB))+length(CAST(result_state AS BLOB))),
 CHECK(result_state<>'complete' OR result_phase=5),
 CHECK(command_kind<>'retire_library' OR (result_kind='library' AND command_sequence=1 AND result_phase=0 AND result_state='retiring')),
 CHECK(command_kind<>'retire_source' OR (result_kind='folder' AND command_sequence=1 AND result_phase=0 AND result_state='retiring')),
 CHECK(command_kind<>'retire_step' OR command_sequence>1),
 PRIMARY KEY(original_operation_id,command_incarnation,result_kind,result_target,command_sequence),
 FOREIGN KEY(original_operation_id,command_incarnation,result_kind,result_target) REFERENCES catalog_removal_progress(original_operation_id,command_incarnation,kind,target)
 ON DELETE NO ACTION ON UPDATE NO ACTION
) WITHOUT ROWID, STRICT;
CREATE INDEX catalog_removal_progress_governor_due ON catalog_removal_progress(job_due_ms) WHERE job_due_ms IS NOT NULL;
CREATE UNIQUE INDEX catalog_removal_operation ON catalog_removal_progress(original_operation_id,command_incarnation,kind,target);
CREATE INDEX catalog_removal_original_library ON catalog_removal_progress(original_library_id);
