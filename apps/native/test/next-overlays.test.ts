test('the phone sheet follows the coast of its actual release velocity', () => {
  const heights = [422, 740];
  assert.deepEqual(releaseSheet(540, 0, heights), {closed: false, index: 0});
  assert.deepEqual(releaseSheet(540, -800, heights), {closed: false, index: 1});
  assert.deepEqual(releaseSheet(540, 800, heights), {closed: false, index: 0});
  assert.deepEqual(releaseSheet(280, 600, heights), {closed: true, index: 0});
  assert.deepEqual(releaseSheet(280, -600, heights), {closed: false, index: 0});
  assert.equal(resistSheet(500, 740), 500);
  assert.ok(resistSheet(800, 740) > 740 && resistSheet(800, 740) < 800);
  assert.ok(resistSheet(-100, 740) > -100 && resistSheet(-100, 740) < 0);
});
test('sheet detents stay visible after rotation and ignore invalid or duplicate heights', () => {
  assert.deepEqual(sheetHeights([740, 422, 422, Infinity, -1], 390, 24), [366]);
  assert.deepEqual(sheetHeights([NaN, 0, -1], 844, 44), [422, 800]);
  assert.deepEqual(sheetHeights(undefined, 844, 44), [422, 800]);
});
test('anchored phone menus preserve width and center/end alignment and flip inside safe bounds', () => {
  const viewport = {width: 390, height: 844};
  const insets = {top: 44, bottom: 34, left: 0, right: 0};
  const anchor = {x: 172, y: 54, width: 46, height: 36};
  const centered = popoverRect(anchor, viewport, {width: 252, height: 230}, insets, 'bottom-center', 6);
  assert.deepEqual(centered, {x: 69, y: 96, width: 252, height: 230});
  const end = popoverRect({x: 342, y: 54, width: 28, height: 32}, viewport, {width: 282, height: 400}, insets, 'bottom-end', 6);
  assert.deepEqual(end, {x: 88, y: 92, width: 282, height: 400});
  const flipped = popoverRect({x: 342, y: 740, width: 28, height: 32}, viewport, {width: 600, height: 400}, insets, 'bottom-end');
  assert.equal(flipped.width, 374);
  assert.equal(flipped.x, 8);
  assert.equal(flipped.y, 334);
  assert.ok(containsPoint(flipped, 20, 350));
  assert.ok(!containsPoint(flipped, 20, 100));
});
