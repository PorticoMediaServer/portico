test('a touched toast retains its remaining time, overlapping holds do not resume it, and replacement cancels old expiry', () => {
  let now = 0;
  let next = 0;
  const jobs = new Map<number, {at: number; run: () => void}>();
  const expired: string[] = [];
  const clock = createToastClock({now: () => now, schedule: (run, delay) => {const id = ++next; jobs.set(id, {at: now + delay, run}); return id;}, cancel: handle => {jobs.delete(handle as number);}}, id => expired.push(id));
  const advance = (ms: number) => {now += ms; for (const [id, job] of [...jobs]) if (job.at <= now) {jobs.delete(id); job.run();}};
  clock.replace('first', 4000);
  advance(1000);
  clock.pause('touch', true);
  clock.pause('background', true);
  advance(10000);
  clock.pause('touch', false);
  advance(4000);
  assert.deepEqual(expired, []);
  clock.pause('background', false);
  advance(2999);
  assert.deepEqual(expired, []);
  clock.replace('second', 8000);
  advance(1);
  assert.deepEqual(expired, []);
  advance(7999);
  assert.deepEqual(expired, ['second']);
  clock.replace('third', 4000);
  clock.pause('touch', true);
  clock.replace('fourth', 4000);
  advance(4000);
  assert.deepEqual(expired, ['second', 'fourth']);
  clock.pause('background', true);
  clock.replace('fifth', 4000);
  advance(10000);
  assert.deepEqual(expired, ['second', 'fourth']);
  clock.dispose();
  advance(10000);
  assert.deepEqual(expired, ['second', 'fourth']);
});

test('Back and Escape reach only the top surface and a lower close cannot steal focus', () => {
  const stack = createOverlayStack();
  const calls: string[] = [];
  const panel = {}, menu = {}, picker = {};
  const closePanel = stack.register(panel, reason => calls.push(`panel:${reason}`));
  const closeMenu = stack.register(menu, reason => calls.push(`menu:${reason}`));
  assert.equal(stack.dismiss('back'), true);
  assert.deepEqual(calls, ['menu:back']);
  const closePicker = stack.register(picker, reason => calls.push(`picker:${reason}`));
  assert.equal(closeMenu(), false);
  assert.equal(stack.isTop(picker), true);
  assert.equal(stack.dismiss('escape'), true);
  assert.deepEqual(calls, ['menu:back', 'picker:escape']);
  assert.equal(closePicker(), true);
  assert.equal(closePicker(), false);
  assert.equal(stack.isTop(panel), true);
  assert.equal(closePanel(), true);
  assert.equal(stack.dismiss('back'), false);
});

test('screen-reader Undo stays persistent across replacement and resumes the authored remainder only when released', () => {
  let now = 0, next = 0;
  const jobs = new Map<number, {at: number; run: () => void}>(), expired: string[] = [];
  const clock = createToastClock({now: () => now, schedule: (run, delay) => {const id = ++next; jobs.set(id, {at: now + delay, run}); return id;}, cancel: handle => jobs.delete(handle as number)}, id => expired.push(id));
  const advance = (ms: number) => {now += ms; for (const [id, job] of [...jobs]) if (job.at <= now) {jobs.delete(id); job.run();}};
  clock.replace('first-undo', 6000);
  advance(1000);
  clock.pause('screen-reader', true);
  advance(60_000);
  assert.deepEqual(expired, []);
  assert.equal(jobs.size, 0);
  clock.pause('screen-reader', false);
  advance(4999);
  assert.deepEqual(expired, []);
  advance(1);
  assert.deepEqual(expired, ['first-undo']);
  clock.pause('screen-reader', true);
  clock.replace('second-undo', 8000);
  clock.replace('replacement-undo', 6000);
  advance(60_000);
  assert.deepEqual(expired, ['first-undo'], 'replacement cannot silently discard the AT hold');
  clock.replace(null, 0);
  clock.pause('screen-reader', false);
  advance(60_000);
  assert.deepEqual(expired, ['first-undo'], 'explicit removal cannot be followed by a stale expiry');
  clock.dispose();
});
